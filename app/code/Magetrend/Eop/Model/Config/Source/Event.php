namespace Magetrend\Eop\Model\Config\Source;

/**
 * Popup trigger events source
 *
 * @category MageTrend
 * @package  Magetend/Eop
 * @author   Edvinas Stulpinas <edwin@magetrend.com>
 * @license  http://opensource.org/licenses/osl-3.0.php Open Software License (OSL 3.0)
 * @link     https://www.magetrend.com/magento-2-exit-intent-popup-extension
 */
class Event implements \Magento\Framework\Option\ArrayInterface
{
    const TRIGGER_EXIT_INTENT = 'exit_intent';

    const TRIGGER_ON_LOAD = 'on_load';

    const TRIGGER_ALL = 'all';

    /**
     * Options getter
     *
     * @return array
     */
    public function toOptionArray()
    {
        $options = $this->toArray();
        $optionArray = [];
        foreach ($options as $value => $label) {
            $optionArray[] = [
                'value' => $value,
                'label' => $label
            ];
        }

        return $optionArray;
    }

    /**
     * Get options in "key-value" format
     *
     * @return array
     */
    public function toArray()
    {
        return [
            self::TRIGGER_EXIT_INTENT           => __('Exit Intent (Default)'),
            self::TRIGGER_ON_LOAD               => __('Page Load'),
            self::TRIGGER_ALL                   => __('Exit Intent & Page Load (Both)'),
        ];
    }
}
