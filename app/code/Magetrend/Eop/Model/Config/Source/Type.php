namespace Magetrend\Eop\Model\Config\Source;

/**
 * Popup content type source
 *
 * @category MageTrend
 * @package  Magetend/Eop
 * @author   Edvinas Stulpinas <edwin@magetrend.com>
 * @license  http://opensource.org/licenses/osl-3.0.php Open Software License (OSL 3.0)
 * @link     https://www.magetrend.com/magento-2-exit-intent-popup-extension
 */
class Type implements \Magento\Framework\Option\ArrayInterface
{
    /**
     * Options getter
     *
     * @return array
     */
    public function toOptionArray()
    {
        $options = $this->toArray();
        $optionArray = [];
        foreach ($options as $value => $label) {
            $optionArray[] = [
                'value' => $value,
                'label' => $label
            ];
        }

        return $optionArray;
    }

    /**
     * Get options in "key-value" format
     *
     * @return array
     */
    public function toArray()
    {
        return [
            'newsletter_subscription_form'      => __('Newsletter Subscription Form'),
            'static_block'                      => __('Static Cms Block'),
            'yes_no_buttons'                    => __('YES/NO Buttons'),
            'contact_form'                      => __('Contact Form'),
        ];
    }
}
